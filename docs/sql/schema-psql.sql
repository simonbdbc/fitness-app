create table public.acrea_profiles (
  user_id uuid primary key references public.user_profiles(id) on delete cascade,
  name text not null,
  objective text,
  objective_code text check (objective_code in ('complete', 'strength', 'cardio', 'proprioception')),
  equipment_mode text check (equipment_mode in ('aucun', 'mixte')),
  weekly_frequency smallint check (weekly_frequency between 1 and 7),
  average_session_minutes smallint check (average_session_minutes between 1 and 180),
  session_minutes_min smallint check (session_minutes_min between 20 and 175 and session_minutes_min % 5 = 0),
  session_minutes_max smallint check (session_minutes_max between 25 and 180 and session_minutes_max % 5 = 0 and session_minutes_max >= session_minutes_min + 5),
  weekly_novelty_percent smallint check (weekly_novelty_percent between 0 and 100 and weekly_novelty_percent % 10 = 0),
  level_test_status text not null default 'required',
  level_test_version integer not null default 0,
  level_test_completed_at timestamptz,
  renforcement_level smallint check (renforcement_level between 1 and 10),
  cardio_level smallint check (cardio_level between 1 and 10),
  proprioception_level smallint check (proprioception_level between 1 and 10),
  preferred_weekdays smallint[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    level_test_status in ('required', 'completed', 'retest')
    and level_test_version >= 0
    and (
      level_test_status <> 'completed'
      or (
        level_test_version > 0
        and level_test_completed_at is not null
        and renforcement_level is not null
        and cardio_level is not null
        and proprioception_level is not null
      )
    )
  )
);

