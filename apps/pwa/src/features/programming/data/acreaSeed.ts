export type ACREAPillarLevelState = Record<ACREAPillar, ACREALevel | null>;

export type ACREAStructuredRestriction =
  | { type: "impactLimit"; maximumImpact: ACREAImpact }
  | { type: "exerciseExclusion"; exerciseCode: string }
  | { type: "pillarLimit"; pillar: ACREAPillar; maximumLevel: ACREALevel }
  | { type: "equipmentExclusion"; equipmentCode: string }
  | { type: "temporaryPain"; muscleGroupCodes: string[] };

type ACREAProfileBase = {
  id: string;
  name: string;
  levelTestStatus: ACREALevelTestStatus;
  levelTestVersion: number;
  levelTestCompletedAt: string | null;
  availableEquipment: string[];
  preferredWeekdays: number[];
  restrictions: ACREAStructuredRestriction[];
  excludedExerciseCodes: string[];
};

export type ACREAProfileState = ACREAProfileBase & {
  objective: string | null;
  objectiveCode: ACREAObjectiveCode | null;
  equipmentMode: ACREAEquipmentMode | null;
  weeklyFrequency: number | null;
  sessionMinutesMin: number | null;
  sessionMinutesMax: number | null;
  weeklyNoveltyPercent: number | null;
  pillarLevels: ACREAPillarLevelState;
};

export type ACREAProfile = ACREAProfileBase & {
  objective: string;
  objectiveCode: ACREAObjectiveCode;
  equipmentMode: ACREAEquipmentMode;
  weeklyFrequency: number;
  sessionMinutesMin: number;
  sessionMinutesMax: number;
  weeklyNoveltyPercent: number;
  pillarLevels: ACREAPillarLevels;
};

export function createEmptyACREAProfile({
  id,
  name,
}: {
  id: string;
  name: string;
}): ACREAProfileState {
  return {
    id,
    name,
    objective: null,
    objectiveCode: null,
    equipmentMode: null,
    weeklyFrequency: null,
    sessionMinutesMin: null,
    sessionMinutesMax: null,
    weeklyNoveltyPercent: null,
    levelTestStatus: "required",
    levelTestVersion: 0,
    levelTestCompletedAt: null,
    pillarLevels: {
      strength: null,
      cardio: null,
      proprioception: null,
    },
    availableEquipment: [],
    preferredWeekdays: [],
    restrictions: [],
    excludedExerciseCodes: [],
  };
}

export function isACREAProfileComplete(
  profile: ACREAProfileState,
): profile is ACREAProfile {
  return (
    Boolean(profile.objective?.trim()) &&
    profile.objectiveCode !== null &&
    profile.equipmentMode !== null &&
    profile.weeklyFrequency !== null &&
    profile.sessionMinutesMin !== null &&
    profile.sessionMinutesMax !== null &&
    profile.weeklyNoveltyPercent !== null &&
    profile.pillarLevels.strength !== null &&
    profile.pillarLevels.cardio !== null &&
    profile.pillarLevels.proprioception !== null &&
    profile.preferredWeekdays.length > 0
  );
}

