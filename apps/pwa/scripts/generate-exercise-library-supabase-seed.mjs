import { readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = path.join(
  appRoot,
  "src/features/catalog/data/exerciseLibrary.json",
);
const evaluationPath = path.resolve(
  appRoot,
  "../../contracts/catalog/acrea-level-evaluation-v4.json",
);
const outputPath = path.join(
  appRoot,
  "supabase/exercise_library_v2_seed.sql",
);

const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
const evaluation = JSON.parse(readFileSync(evaluationPath, "utf8"));
const exerciseCount = artifact.exercises?.length;
const templateCount = artifact.sessionTemplates?.length;
if (
  artifact.release?.code !== "exercise-library-v2" ||
  !Number.isInteger(exerciseCount) ||
  exerciseCount < 1 ||
  artifact.release.expectedExerciseCount !== exerciseCount ||
  artifact.summary?.exerciseCount !== exerciseCount ||
  !Number.isInteger(templateCount) ||
  templateCount < 3 ||
  artifact.summary?.templateCount !== templateCount ||
  evaluation.catalogReleaseCode !== artifact.release.code
) {
  throw new Error("Canonical exercise-library artifacts are invalid.");
}

const payload = JSON.stringify(artifact.exercises);
const templates = JSON.stringify(artifact.sessionTemplates);
const mappings = JSON.stringify(evaluation.exercises);
const sql = `-- Generated by apps/pwa/scripts/generate-exercise-library-supabase-seed.mjs.
-- Do not edit: update docs/bibliotheque and regenerate instead.
begin;

update public.catalog_releases
set source_revision = '${artifact.revision}',
    expected_exercise_count = ${exerciseCount},
    updated_at = now()
where code = 'exercise-library-v2';

with exercise_seed as (
  select * from jsonb_to_recordset($acrea_exercises$
${payload}
$acrea_exercises$::jsonb) as value(
  slug text, "labelFr" text, "labelEn" text, "categorySlug" text,
  "equipmentSlug" text, "pillarSlug" text, difficulty integer,
  "impactSlug" text, "familySlug" text, "typeSlug" text,
  "muscleGroupSlugs" jsonb, "programmingStatus" text,
  "movementDescription" text, "startPosition" text,
  "outboundExecution" text, "returnExecution" text,
  "adaptedVersion" text, tips text, errors text, "isActive" boolean,
  "reviewStatus" text, "translationStatus" text, media jsonb
)
)
insert into public.catalog_exercises (
  code, slug, label, label_fr, label_en, category_slug, equipment_slug,
  release_id, source_key, pillar_id, difficulty, impact_id, family_id, type_id,
  equipment_id, movement_description, start_position, outbound_execution,
  return_execution, adapted_version, tips, errors, is_active, review_status,
  translation_status, programming_status, updated_at
)
select value.slug, value.slug, value."labelFr", value."labelFr", value."labelEn",
       value."categorySlug", value."equipmentSlug", release.id,
       release.code || ':' || value.slug, pillar.id,
       value.difficulty, impact.id, family.id, exercise_type.id, equipment.id,
       value."movementDescription", value."startPosition", value."outboundExecution",
       value."returnExecution", value."adaptedVersion", value.tips, value.errors,
       value."isActive", value."reviewStatus", value."translationStatus",
       value."programmingStatus", now()
from exercise_seed value
join public.catalog_releases release on release.code = 'exercise-library-v2'
join public.catalog_pillars pillar on pillar.code = value."pillarSlug"
join public.catalog_impacts impact on impact.code = value."impactSlug"
join public.catalog_families family on family.code = value."familySlug"
join public.catalog_types exercise_type on exercise_type.code = value."typeSlug"
join public.catalog_equipment equipment on equipment.code = value."equipmentSlug";

with exercise_seed as (
  select * from jsonb_to_recordset($acrea_exercises$
${payload}
$acrea_exercises$::jsonb) as value(slug text, "muscleGroupSlugs" jsonb, media jsonb)
)
insert into public.catalog_exercise_muscle_groups (exercise_id, muscle_group_id)
select exercise.id, muscle_group.id
from exercise_seed value
join public.catalog_exercises exercise on exercise.slug = value.slug
cross join lateral jsonb_array_elements_text(value."muscleGroupSlugs") muscle(code)
join public.catalog_muscle_groups muscle_group on muscle_group.code = muscle.code;

with exercise_seed as (
  select * from jsonb_to_recordset($acrea_exercises$
${payload}
$acrea_exercises$::jsonb) as value(slug text, "equipmentSlug" text)
)
insert into public.catalog_exercise_equipment_options (exercise_id, option_index, kind)
select exercise.id, 0,
       case when value."equipmentSlug" = 'no-equipment' then 'bodyweight' else 'equipment' end
from exercise_seed value
join public.catalog_exercises exercise on exercise.slug = value.slug;

with exercise_seed as (
  select * from jsonb_to_recordset($acrea_exercises$
${payload}
$acrea_exercises$::jsonb) as value(slug text, "equipmentSlug" text)
)
insert into public.catalog_exercise_equipment_option_items (option_id, equipment_id)
select option.id, equipment.id
from exercise_seed value
join public.catalog_exercises exercise on exercise.slug = value.slug
join public.catalog_exercise_equipment_options option
  on option.exercise_id = exercise.id and option.option_index = 0
join public.catalog_equipment equipment on equipment.code = value."equipmentSlug"
where value."equipmentSlug" <> 'no-equipment';

with exercise_seed as (
  select * from jsonb_to_recordset($acrea_exercises$
${payload}
$acrea_exercises$::jsonb) as value(slug text, media jsonb)
)
insert into public.catalog_exercise_media (
  exercise_id, kind, uri, file_name, mime_type, width, height, frame_count,
  loop_count, sha256, source_url, status, updated_at
)
select exercise.id, asset->>'kind', asset->>'uri', asset->>'fileName',
       asset->>'mimeType', (asset->>'width')::integer, (asset->>'height')::integer,
       (asset->>'frameCount')::integer, nullif(asset->>'loopCount', '')::integer,
       asset->>'sha256', null, asset->>'status', (asset->>'updatedAt')::timestamptz
from exercise_seed value
join public.catalog_exercises exercise on exercise.slug = value.slug
cross join lateral jsonb_array_elements(value.media) asset;

with template_seed as (
  select * from jsonb_to_recordset($acrea_templates$
${templates}
$acrea_templates$::jsonb) as value(
  code text, title text, description text, "exerciseSlug" text, phase text,
  "isActive" boolean, "sourceStatus" text, "updatedAt" timestamptz, levels jsonb
)
)
insert into public.catalog_session_templates (
  code, title, description, exercise_id, phase, is_active, source_status, updated_at
)
select value.code, value.title, value.description, exercise.id, value.phase,
       value."isActive", value."sourceStatus", value."updatedAt"
from template_seed value
join public.catalog_exercises exercise on exercise.slug = value."exerciseSlug";

with template_seed as (
  select * from jsonb_to_recordset($acrea_templates$
${templates}
$acrea_templates$::jsonb) as value(code text, levels jsonb, "updatedAt" timestamptz)
)
insert into public.catalog_session_template_levels (
  session_template_id, level, updated_at
)
select template.id, level.value::smallint, value."updatedAt"
from template_seed value
join public.catalog_session_templates template on template.code = value.code
cross join lateral jsonb_array_elements_text(value.levels) level(value);

with mapping_seed as (
  select * from jsonb_to_recordset($acrea_mappings$
${mappings}
$acrea_mappings$::jsonb) as value(
    "evaluationExerciseCode" text, "exerciseSlug" text, pillar text,
    "protocolVariant" text, "mappingConfidence" text, "phase1" jsonb,
    "phase2" jsonb, "levelThresholds" jsonb
  )
)
insert into public.acrea_level_evaluation_exercise_mappings (
  protocol_version, evaluation_exercise_code, exercise_slug, pillar,
  protocol_variant, confidence, count_unit, phase_1_series,
  phase_1_repetitions, phase_2_series, phase_2_repetitions, phase_3_series,
  level_2_minimum, level_3_minimum, validated_at, updated_at
)
select 4, value."evaluationExerciseCode", value."exerciseSlug", value.pillar,
       value."protocolVariant", value."mappingConfidence", 'reps',
       (value."phase1"->>'series')::integer,
       (value."phase1"->>'repetitions')::integer,
       (value."phase2"->>'series')::integer,
       (value."phase2"->>'repetitions')::integer, 1,
       (value."levelThresholds"->>'level2Minimum')::integer,
       (value."levelThresholds"->>'level3Minimum')::integer, now(), now()
from mapping_seed value;

-- V3 preferences stored catalogue codes. The reset migration kept them in a
-- staging table until the V2 exercises existed; map them now to V2 slugs.
insert into public.acrea_level_evaluation_preferences (
  user_id, protocol_version, evaluation_exercise_code, exercise_slug,
  appreciation_average, sample_count, evaluated_at, sync_status
)
select legacy.user_id, legacy.protocol_version, mapping.evaluation_exercise_code,
       mapping.exercise_slug, legacy.appreciation_average, legacy.sample_count,
       legacy.evaluated_at, 'synced'
from public._acrea_level_evaluation_preferences_pre_beta legacy
join (values
  ('renforcement-pompe-stricte', 'renforcement-strict-pushups', 'push-up'),
  ('renforcement-squat-poids-du-corps', 'renforcement-bodyweight-squats', 'air-squat'),
  ('cardio-burpee-sans-pompe', 'cardio-burpee-sans-pompe', 'burpee'),
  ('cardio-mountain-climber-classique', 'cardio-mountain-climber-controle', 'mountain-climber'),
  ('proprioception-releve-de-jambes-au-sol', 'proprioception-leg-raise', 'lying-leg-raise'),
  ('proprioception-planche-lean', 'proprioception-planche-lean', 'lean-planche')
) as mapping(legacy_catalog_exercise_code, evaluation_exercise_code, exercise_slug)
  on mapping.legacy_catalog_exercise_code = legacy.catalog_exercise_code
on conflict (user_id, protocol_version, exercise_slug) do update set
  evaluation_exercise_code = excluded.evaluation_exercise_code,
  appreciation_average = excluded.appreciation_average,
  sample_count = excluded.sample_count,
  evaluated_at = excluded.evaluated_at,
  sync_status = 'synced';

drop table public._acrea_level_evaluation_preferences_pre_beta;

commit;
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== sql) {
    throw new Error("exercise_library_v2_seed.sql is stale.");
  }
  console.log("[exercise-library] Supabase seed is current.");
} else {
  writeFileSync(outputPath, sql);
  console.log(`[exercise-library] generated Supabase seed for ${exerciseCount} complete exercises.`);
}
