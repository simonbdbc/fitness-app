#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import catalogSeed from "../src/features/catalog/data/catalogSeed.json" with {
  type: "json",
};
import { canonicalEquipment } from "../src/features/catalog/services/equipmentRequirements.ts";
import { generateBaseFormatSeedSql } from "./generate-base-format-seed.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "..");
const outputPath = path.join(projectRoot, "supabase", "seed.sql");
const checkOnly = process.argv.includes("--check");

if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  throw new Error("Usage: node scripts/generate-supabase-v2-seed.mjs [--check]");
}

const expected = renderSeed();
if (checkOnly) {
  const current = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, "utf8")
    : "";
  if (current !== expected) {
    throw new Error("supabase/seed.sql is not the generated structural seed");
  }
  console.log("Supabase structural seed is up to date.");
} else {
  fs.writeFileSync(outputPath, expected);
  console.log(`Generated ${path.relative(projectRoot, outputPath)}.`);
}

function renderSeed() {
  if (
    catalogSeed.exercises.length !== 0 ||
    catalogSeed.sessionTemplates.length !== 0 ||
    catalogSeed.sessionTemplateLevels.length !== 0
  ) {
    throw new Error(
      "The structural catalog seed must not contain exercises or session templates.",
    );
  }
  if (canonicalEquipment.length !== 25) {
    throw new Error(
      `Expected 25 canonical equipment rows, found ${canonicalEquipment.length}.`,
    );
  }

  const equipmentValues = canonicalEquipment
    .map(
      (equipment) =>
        `  (${sqlText(equipment.code)}, ${sqlText(equipment.label)}, ${sqlText(equipment.labelEn)}, ${sqlText(equipment.category)})`,
    )
    .join(",\n");

  return `-- Generated by scripts/generate-supabase-v2-seed.mjs. Do not edit manually.
-- Structural data only. Exercises and media are generated exclusively from
-- docs/bibliotheque into exercise_library_v2_seed.sql.

${generateBaseFormatSeedSql("psql").trim()}

begin;

insert into public.catalog_equipment (code, label, label_en, category) values
${equipmentValues}
on conflict (code) do update
set label = excluded.label,
    label_en = excluded.label_en,
    category = excluded.category;

do $$
begin
  if (select count(*) from public.catalog_equipment
      where code in (${canonicalEquipment.map(({ code }) => sqlText(code)).join(", ")})) <> 25 then
    raise exception 'structural seed did not upsert 25 canonical equipment rows';
  end if;
end $$;

commit;
`;
}

function sqlText(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}
