do $$
declare
  duplicate_week record;
  unresolved_sessions bigint;
  unresolved_feedback bigint;
begin
  select profile_id, iso_week_year, iso_week_number, count(*) as row_count
  into duplicate_week
  from public.programs
  where schema_version = 2
  group by profile_id, iso_week_year, iso_week_number
  having count(*) > 1
  limit 1;

  if found then
    raise exception 'weekly AI migration: duplicate program for profile %, ISO week %-% (% rows)',
      duplicate_week.profile_id, duplicate_week.iso_week_year,
      duplicate_week.iso_week_number, duplicate_week.row_count;
  end if;

  select count(*) into unresolved_sessions
  from public.sessions
  where session_template_id is null or exercise_id is null or exercise_code is null
     or format_id is null or format_code is null;
  if unresolved_sessions <> 0 then
    raise exception 'weekly AI migration: % session(s) have unresolved catalog references', unresolved_sessions;
  end if;

  select count(*) into unresolved_feedback
  from public.session_feedback
  where session_template_id is null or exercise_id is null or exercise_code is null
     or format_id is null;
  if unresolved_feedback <> 0 then
    raise exception 'weekly AI migration: % feedback row(s) have unresolved catalog references', unresolved_feedback;
  end if;
end $$;

