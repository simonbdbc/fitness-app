-- The French exercise library is the sole catalogue authority.  This
-- migration deliberately clears generated catalogue data and programmes.
-- Completed ACREA evaluations are preserved and remapped to V2 identifiers;
-- accounts, profiles and authentication are preserved.
begin;

create table if not exists public.catalog_releases (
  id bigint generated by default as identity primary key,
  code text not null unique check (btrim(code) <> ''),
  source text not null check (btrim(source) <> ''),
  source_revision text not null default '',
  locale text not null check (btrim(locale) <> ''),
  expected_exercise_count integer not null check (expected_exercise_count > 0),
  status text not null check (status in ('prepared', 'active', 'archived')),
  license_id text,
  activation_backup_reference text,
  activation_diff_reference text,
  created_at timestamptz not null,
  activated_at timestamptz,
  archived_at timestamptz,
  updated_at timestamptz not null
);
create unique index if not exists catalog_releases_one_active_idx
  on public.catalog_releases ((1)) where status = 'active';
alter table public.catalog_releases enable row level security;
grant select on public.catalog_releases to anon, authenticated;
drop policy if exists "Catalog releases are readable" on public.catalog_releases;
create policy "Catalog releases are readable"
  on public.catalog_releases for select to anon, authenticated using (true);

drop table if exists public.catalog_exercise_successors cascade;
drop table if exists public.acrea_level_evaluation_legacy_aliases cascade;
drop table if exists public.catalog_release_activation_exercise_states cascade;
drop table if exists public.catalog_release_activation_release_states cascade;
drop table if exists public.catalog_release_activations cascade;

create table if not exists public.catalog_exercise_media (
  id bigint generated by default as identity primary key,
  exercise_id bigint not null references public.catalog_exercises(id) on delete cascade,
  kind text not null check (kind in ('poster', 'animation')),
  uri text not null,
  file_name text not null,
  mime_type text not null check (mime_type = 'image/webp'),
  width integer not null check (width > 0),
  height integer not null check (height > 0),
  frame_count integer not null check (frame_count > 0),
  loop_count integer check (loop_count is null or loop_count >= 0),
  sha256 text not null,
  source_url text,
  status text not null check (status in ('ready', 'missing', 'invalid')),
  updated_at timestamptz not null,
  unique (exercise_id, kind)
);
alter table public.catalog_exercise_media
  add column if not exists source_url text;
alter table public.catalog_exercise_media enable row level security;
grant select on public.catalog_exercise_media to anon, authenticated;
drop policy if exists "Catalog exercise media are readable" on public.catalog_exercise_media;
create policy "Catalog exercise media are readable"
  on public.catalog_exercise_media for select to anon, authenticated using (true);

truncate table public.session_feedback,
  public.sessions,
  public.seances,
  public.trainings,
  public.programs,
  public.acrea_exercise_progressions,
  public.acrea_profile_excluded_exercises
restart identity cascade;

-- The beta keeps identities, profiles and equipment declarations. Profiles
-- with a completed evaluation retain their assessed levels; only profiles that
-- had not completed an evaluation restart that journey.
update public.acrea_profiles
set level_test_status = 'required',
    level_test_version = 0,
    level_test_completed_at = null,
    updated_at = now()
where level_test_status is distinct from 'completed';

do $$
begin
  if to_regclass('public.acrea_level_evaluation_preferences') is not null then
    alter table public.acrea_level_evaluation_preferences
      rename to _acrea_level_evaluation_preferences_pre_beta;
    alter table public._acrea_level_evaluation_preferences_pre_beta
      drop constraint if exists acrea_level_evaluation_preferences_catalog_exercise_code_fkey;
  end if;
end $$;
drop table if exists public.acrea_level_evaluation_exercise_mappings cascade;

create table if not exists public._acrea_level_evaluation_preferences_pre_beta (
  user_id uuid not null,
  protocol_version integer not null,
  evaluation_exercise_code text not null,
  catalog_exercise_code text not null,
  appreciation_average numeric(3, 2) not null,
  sample_count smallint not null,
  evaluated_at timestamptz not null
);

truncate table public.catalog_exercise_media,
  public.catalog_exercise_equipment_option_items,
  public.catalog_exercise_equipment_options,
  public.catalog_exercise_muscle_groups,
  public.catalog_session_template_levels,
  public.catalog_session_templates,
  public.catalog_exercises,
  public.catalog_releases
restart identity cascade;

alter table public.catalog_pillars
  drop constraint if exists catalog_pillars_code_check;

update public.catalog_pillars
set code = case code
      when 'echauffement' then 'warm-up'
      when 'renforcement' then 'strength'
      when 'assouplissement' then 'flexibility'
      else code
    end,
    label = case code
      when 'echauffement' then 'Échauffement'
      when 'renforcement' then 'Renforcement'
      when 'proprioception' then 'Proprioception'
      when 'assouplissement' then 'Assouplissement'
      else label
    end;

alter table public.catalog_pillars
  add constraint catalog_pillars_code_check
  check (code in ('warm-up', 'cardio', 'strength', 'proprioception', 'flexibility'));

alter table public.catalog_exercises
  add column if not exists release_id bigint references public.catalog_releases(id) on delete restrict,
  add column if not exists source_key text not null default '',
  add column if not exists slug text,
  add column if not exists label_fr text,
  add column if not exists label_en text,
  add column if not exists category_slug text,
  add column if not exists equipment_slug text,
  add column if not exists is_active boolean not null default true,
  add column if not exists review_status text not null default 'a_verifier',
  add column if not exists translation_status text not null default 'pending',
  add column if not exists programming_status text not null default 'ineligible',
  add column if not exists updated_at timestamptz not null default now();

update public.catalog_exercises
set slug = coalesce(slug, code),
    label_fr = coalesce(label_fr, label),
    label_en = coalesce(label_en, label),
    category_slug = coalesce(category_slug, ''),
    equipment_slug = coalesce(equipment_slug, 'no-equipment');

alter table public.catalog_exercises
  alter column slug set not null,
  alter column label_fr set not null,
  alter column label_en set not null,
  alter column category_slug set not null,
  alter column equipment_slug set not null;

create unique index if not exists catalog_exercises_slug_unique
  on public.catalog_exercises (slug);
create unique index if not exists catalog_exercises_release_source_key_unique
  on public.catalog_exercises (release_id, source_key)
  where release_id is not null and source_key <> '';

create table public.acrea_level_evaluation_exercise_mappings (
  protocol_version integer not null check (protocol_version >= 4),
  evaluation_exercise_code text not null,
  exercise_slug text not null references public.catalog_exercises(slug) on delete restrict,
  pillar text not null check (pillar in ('strength', 'cardio', 'proprioception')),
  protocol_variant text not null,
  confidence text not null check (confidence in ('high', 'medium')),
  count_unit text not null default 'reps' check (count_unit = 'reps'),
  phase_1_series integer not null check (phase_1_series > 0),
  phase_1_repetitions integer not null check (phase_1_repetitions > 0),
  phase_2_series integer not null check (phase_2_series > 0),
  phase_2_repetitions integer not null check (phase_2_repetitions > 0),
  phase_3_series integer not null default 1 check (phase_3_series = 1),
  level_2_minimum integer not null check (level_2_minimum >= 0),
  level_3_minimum integer not null check (level_3_minimum > level_2_minimum),
  validated_at timestamptz,
  updated_at timestamptz not null,
  primary key (protocol_version, evaluation_exercise_code),
  unique (protocol_version, exercise_slug)
);
alter table public.acrea_level_evaluation_exercise_mappings enable row level security;
grant select on public.acrea_level_evaluation_exercise_mappings to authenticated;
create policy "Authenticated users read canonical V4 mappings"
  on public.acrea_level_evaluation_exercise_mappings for select to authenticated
  using (true);

create table public.acrea_level_evaluation_preferences (
  user_id uuid not null references public.acrea_profiles(user_id) on delete cascade,
  protocol_version integer not null check (protocol_version >= 3),
  evaluation_exercise_code text not null,
  exercise_slug text not null references public.catalog_exercises(slug) on delete restrict,
  appreciation_average numeric(3, 2) not null check (appreciation_average between 1 and 5),
  sample_count smallint not null check (sample_count > 0),
  evaluated_at timestamptz not null,
  sync_status text not null default 'pending' check (sync_status in ('pending', 'synced', 'failed')),
  primary key (user_id, protocol_version, exercise_slug)
);

-- V3 preferences are retained in _acrea_level_evaluation_preferences_pre_beta.
-- The generated V2 seed remaps them only after their target exercise slugs
-- exist, then removes this one-shot staging table.

alter table public.acrea_level_evaluation_preferences enable row level security;
grant select, insert, update, delete on public.acrea_level_evaluation_preferences to authenticated;
create policy "Users manage own canonical evaluation preferences"
  on public.acrea_level_evaluation_preferences for all to authenticated
  using (user_id = (select auth.uid()) or (select private.is_admin()))
  with check (user_id = (select auth.uid()) or (select private.is_admin()));

insert into public.catalog_releases (
  code, source, source_revision, locale, expected_exercise_count, status,
  license_id, created_at, activated_at, archived_at, updated_at
) values (
  'exercise-library-v2', 'docs/bibliotheque', '', 'fr', 707, 'active',
  null, now(), now(), null, now()
);

-- Exercise rows and their local WebP metadata are loaded only from the
-- generated French library seed.  The admin interface has no write access.
revoke insert, update, delete on public.catalog_exercises from authenticated;
revoke insert, update, delete on public.catalog_exercise_media from authenticated;
revoke insert, update, delete on public.catalog_exercise_equipment_options from authenticated;
revoke insert, update, delete on public.catalog_exercise_equipment_option_items from authenticated;

commit;
