-- Etat BDD local courant: briques formats + socle catalogue metier.
-- Source applicative actuelle: apps/pwa/supabase/reset-local-format-schema.sql.

create table public.catalog_pillars (
  id bigint generated by default as identity primary key,
  code text not null unique check (code in ('echauffement', 'cardio', 'renforcement', 'proprioception', 'assouplissement')),
  label text not null
);

create table public.catalog_impacts (
  id bigint generated by default as identity primary key,
  code text not null unique check (code in ('faible', 'modere', 'eleve')),
  label text not null
);

create table public.catalog_families (
  id bigint generated by default as identity primary key,
  code text not null unique check (code in ('corps-entier', 'haut-du-corps', 'bas-du-corps')),
  label text not null
);

create table public.catalog_types (
  id bigint generated by default as identity primary key,
  code text not null unique check (code in ('echauffement', 'cardio', 'gainage', 'force', 'endurance', 'proprioception', 'assouplissement')),
  label text not null
);

create table public.catalog_muscle_groups (
  id bigint generated by default as identity primary key,
  code text not null unique check (code in ('bras', 'epaules', 'dos', 'jambes', 'fessiers', 'abdos', 'pecs')),
  label text not null
);

create table public.catalog_equipment (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null
);

create table public.catalog_exercises (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  pillar_id bigint not null references public.catalog_pillars(id) on delete restrict,
  difficulty smallint not null check (difficulty between 1 and 10),
  impact_id bigint not null references public.catalog_impacts(id) on delete restrict,
  family_id bigint not null references public.catalog_families(id) on delete restrict,
  type_id bigint not null references public.catalog_types(id) on delete restrict,
  equipment_id bigint not null references public.catalog_equipment(id) on delete restrict,
  regression_exercise_id bigint references public.catalog_exercises(id) on delete set null,
  progression_exercise_id bigint references public.catalog_exercises(id) on delete set null,
  movement_description text not null default '',
  start_position text not null default '',
  outbound_execution text not null default '',
  return_execution text not null default '',
  adapted_version text not null default '',
  tips text not null default '',
  errors text not null default ''
);

create table public.catalog_exercise_muscle_groups (
  exercise_id bigint not null references public.catalog_exercises(id) on delete cascade,
  muscle_group_id bigint not null references public.catalog_muscle_groups(id) on delete cascade,
  primary key (exercise_id, muscle_group_id)
);

create table public.catalog_rests (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  rest_seconds integer not null check (rest_seconds >= 0),
  updated_at timestamptz not null
);

create table public.catalog_series (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  series integer not null check (series > 0),
  updated_at timestamptz not null
);

create table public.catalog_repetitions (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  reps integer check (reps is null or reps > 0),
  updated_at timestamptz not null
);

create table public.catalog_intervals (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  effort_seconds integer not null check (effort_seconds > 0),
  updated_at timestamptz not null
);

create table public.catalog_formats (
  id bigint generated by default as identity primary key,
  code text not null unique,
  format_type text not null check (format_type in ('repetitions', 'intervalles')),
  series_id bigint not null references public.catalog_series(id) on delete restrict,
  repetitions_id bigint references public.catalog_repetitions(id) on delete restrict,
  rest_id bigint not null references public.catalog_rests(id) on delete restrict,
  interval_id bigint references public.catalog_intervals(id) on delete restrict,
  label text not null,
  description text not null default '',
  source_status text not null,
  updated_at timestamptz not null,
  check (
    (format_type = 'repetitions' and repetitions_id is not null and interval_id is null)
    or
    (format_type = 'intervalles' and interval_id is not null and repetitions_id is null)
  )
);

create table public.catalog_session_templates (
  id bigint generated by default as identity primary key,
  code text not null unique,
  title text not null,
  description text not null default '',
  exercise_id bigint not null references public.catalog_exercises(id) on delete restrict,
  is_active boolean not null default true,
  source_status text not null,
  updated_at timestamptz not null
);

create table public.catalog_session_template_levels (
  session_template_id bigint not null references public.catalog_session_templates(id) on delete cascade,
  level smallint not null check (level between 1 and 10),
  updated_at timestamptz not null,
  primary key (session_template_id, level)
);

