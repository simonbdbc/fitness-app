create index catalog_formats_series_idx on public.catalog_formats (series_id);
create index catalog_formats_repetitions_idx on public.catalog_formats (repetitions_id);
create index catalog_formats_intervals_idx on public.catalog_formats (interval_id);
create index catalog_formats_rests_idx on public.catalog_formats (rest_id);
create index catalog_session_templates_exercise_idx on public.catalog_session_templates (exercise_id, is_active, title);
