-- ACREA Fitness - reset local du socle catalogue metier.
-- Local only: supprime les tables public actuelles et recree les briques formats,
-- les taxonomies et les exercices catalogue.

do $$
declare
  table_record record;
begin
  for table_record in
    select schemaname, tablename
    from pg_tables
    where schemaname = 'public'
  loop
    execute format(
      'drop table if exists %I.%I cascade',
      table_record.schemaname,
      table_record.tablename
    );
  end loop;
end $$;

