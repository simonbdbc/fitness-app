create table if not exists exercises (
    id bigint generated by default as identity primary key,
    name text not null unique,
    pillar text not null check (pillar in ('renforcement', 'cardio', 'proprioception')),
    family text not null,
    level_min smallint not null constraint exercises_level_min_range check (level_min between 1 and 10),
    level_max smallint not null constraint exercises_level_max_range check (level_max >= level_min and level_max <= 10),
    equipment text not null,
    mode_compatibility text not null,
    timer_compatibility text not null,
    impact text not null check (impact in ('faible', 'modere', 'eleve')),
    explanation text not null,
    regression text not null,
    progression text not null,
    source_status text not null default 'original projet',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists profiles (
    id bigint generated by default as identity primary key,
    display_name text not null,
    objective text not null,
    equipment_mode text not null check (equipment_mode in ('strict', 'mixte')),
    weekly_frequency smallint not null check (weekly_frequency between 2 and 7),
    average_session_minutes smallint not null check (average_session_minutes between 20 and 75),
    pillar_levels jsonb not null,
    available_equipment text[] not null default '{}',
    active_variant_tags text[] not null default '{}',
    restrictions text[] not null default '{}',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists level_tests (
    id bigint generated by default as identity primary key,
    profile_id bigint references profiles(id) on delete cascade,
    input jsonb not null,
    result jsonb not null,
    created_at timestamptz not null default now()
);

create table if not exists weekly_programs (
    id bigint generated by default as identity primary key,
    profile_id bigint references profiles(id) on delete cascade,
    week_number smallint not null,
    generated_by text not null,
    payload jsonb not null,
    created_at timestamptz not null default now()
);

