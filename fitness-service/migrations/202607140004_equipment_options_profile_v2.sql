alter table profiles drop constraint if exists profiles_equipment_mode_check;
update profiles set equipment_mode = case
  when cardinality(available_equipment) = 0 then 'aucun' else 'mixte' end;
alter table profiles add constraint profiles_equipment_mode_check
  check (equipment_mode in ('aucun', 'mixte'));

create table if not exists catalog_equipment (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  category text not null check (category in ('maison', 'sport')),
  unique (label)
);

create table if not exists catalog_exercise_equipment_options (
  id bigint generated by default as identity primary key,
  exercise_id bigint not null references catalog_exercises(id) on delete cascade,
  option_index integer not null check (option_index >= 0),
  kind text not null check (kind in ('bodyweight', 'equipment')),
  unique (exercise_id, option_index)
);

create table if not exists catalog_exercise_equipment_option_items (
  option_id bigint not null references catalog_exercise_equipment_options(id) on delete cascade,
  equipment_id bigint not null references catalog_equipment(id) on delete restrict,
  primary key (option_id, equipment_id)
);

